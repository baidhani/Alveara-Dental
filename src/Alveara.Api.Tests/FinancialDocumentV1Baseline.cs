using System.Runtime.CompilerServices;
using System.Text.Json;
using Alveara.Api.Architecture.Billing;
using Xunit;

namespace Alveara.Api.Tests;

/// <summary>
/// ALV-N021 A1 (A1-DECISION-01): the version-1 statements and receipts whose canonical bytes were captured from the builder BEFORE template version 2 existed. The cases include evening services (practice
/// evening, already the next UTC day), each aging boundary, a DST change and a year end, so they are exactly the documents a careless switch to practice-local days would break. The captured file
/// (<c>Fixtures/financial-documents-v1-baseline.json</c>) is evidence: it is never regenerated by the new code (the capture refuses to overwrite it).
/// </summary>
public static class FinancialDocumentV1Cases
{
    public sealed record Case(string Name, string Type, LedgerSnapshot Snapshot, FinancialCutOffs CutOffs, DocumentEnvelope Envelope, int? PaymentNumber);

    private static readonly DocumentParty Ann = new(Guid.Parse("00000000-0000-0000-0000-0000000000a1"), "Ann Lee", true);
    private static readonly DocumentParty Bo = new(Guid.Parse("00000000-0000-0000-0000-0000000000b2"), "Bo Lee", false);
    private static readonly DocumentEnvelope Plain = new(Ann, Ann, "Self", "USD");
    private static readonly DocumentEnvelope Full = new(Ann, Bo, "Recorded", "USD", new DocumentPractice("Alder Dental", "555-0100", "1 Main St, Springfield"));

    private static DateTimeOffset Utc(int y, int mo, int d, int h, int mi) => new(y, mo, d, h, mi, 0, TimeSpan.Zero);

    private static SnapshotEntry Charge(int n, decimal amount, DateTimeOffset service, string code = "D1110", string desc = "Cleaning") =>
        new(n, BillingKinds.Charge, amount, null, null, null, code, desc, null, null, service, service);
    private static SnapshotEntry Payment(int n, decimal amount, DateTimeOffset at) => new(n, BillingKinds.Payment, -amount, null, null, null, null, null, "Cash", null, at, at);
    private static SnapshotEntry Refund(int n, int payment, decimal amount, DateTimeOffset at) => new(n, BillingKinds.Refund, amount, null, payment, null, null, null, "Cash", "Patient request", at, at);
    private static SnapshotEntry Reversal(int n, int undone, decimal undoneAmount, DateTimeOffset at) => new(n, BillingKinds.Reversal, -undoneAmount, undone, null, null, null, null, null, "Entered in error", at, at);

    /// <summary>Chicago 22:42 on 1 Jan 2030 is 04:42 UTC on 2 Jan: the evening case where UTC and practice days differ.</summary>
    public static readonly DateTimeOffset EveningService = Utc(2030, 1, 2, 4, 42);

    public static IReadOnlyList<Case> All { get; } = Build();

    private static List<Case> Build()
    {
        var list = new List<Case>();
        // aging boundaries: one evening charge, statements as of the morning of each boundary day (Chicago 09:00 = 15:00 UTC); the UTC age and the practice-day age differ by one
        foreach (var days in new[] { 30, 31, 60, 61, 90, 91 })
        {
            var asOf = EveningService.AddDays(days).Date.AddHours(15);
            list.Add(new($"statement-evening-utc-age-{days}", FinancialDocumentTypes.Statement, new([Charge(1, 120m, EveningService)], [], []), new(1, 0, 0, 0, new DateTimeOffset(asOf, TimeSpan.Zero)), Plain, null));
        }
        // a full statement: two charges (one evening, one morning), a payment applied to both, a refund that releases part of an application, a reversed charge, unapplied money, hostile text, practice details
        var rich = new LedgerSnapshot(
            [Charge(1, 100m, EveningService), Charge(2, 250.5m, Utc(2030, 1, 10, 16, 0), "D2740", "Crown, \"porcelain\""), Payment(3, 200m, Utc(2030, 1, 11, 23, 30)), Refund(4, 3, 30m, Utc(2030, 1, 12, 2, 15)),
             Charge(5, 75m, Utc(2030, 1, 12, 3, 0), "=CMD", "@x"), Reversal(6, 5, 75m, Utc(2030, 1, 12, 3, 5))],
            [new(1, 3, 1, 100m), new(2, 3, 2, 80m)], [new(1, 3, 2, 30m, 4)]);
        list.Add(new("statement-rich", FinancialDocumentTypes.Statement, rich, new(6, 2, 1, 0, Utc(2030, 2, 20, 5, 30)), Full, null));
        // DST: service the evening before the spring change (Chicago, 9 Mar 2030 21:30 CST = 10 Mar 03:30 UTC), statement 31 practice days later, after the change
        list.Add(new("statement-dst-spring", FinancialDocumentTypes.Statement, new([Charge(1, 60m, Utc(2030, 3, 10, 3, 30))], [], []), new(1, 0, 0, 0, Utc(2030, 4, 10, 4, 30)), Plain, null));
        // DST: service the evening of the autumn change (Chicago, 3 Nov 2030 19:15 CST = 4 Nov 01:15 UTC)
        list.Add(new("statement-dst-autumn", FinancialDocumentTypes.Statement, new([Charge(1, 45m, Utc(2030, 11, 4, 1, 15))], [], []), new(1, 0, 0, 0, Utc(2030, 12, 4, 14, 0)), Full, null));
        // year end: service 31 Dec 2030 20:00 Chicago (= 1 Jan 2031 02:00 UTC), statement as of 31 Jan 2031 evening Chicago
        list.Add(new("statement-year-end", FinancialDocumentTypes.Statement, new([Charge(1, 10m, Utc(2031, 1, 1, 2, 0))], [], []), new(1, 0, 0, 0, Utc(2031, 2, 1, 1, 0)), Plain, null));
        // receipts: no aging, but they carry the template version, so they are frozen too
        list.Add(new("receipt-rich", FinancialDocumentTypes.Receipt, rich, new(6, 2, 1, 0, Utc(2030, 2, 20, 5, 30)), Full, 3));
        list.Add(new("receipt-plain", FinancialDocumentTypes.Receipt, new([Charge(1, 50m, EveningService), Payment(2, 50m, Utc(2030, 1, 2, 5, 0))], [new(1, 2, 1, 50m)], []), new(2, 1, 0, 0, Utc(2030, 1, 2, 5, 0)), Plain, 2));
        return list;
    }
}

/// <summary>One captured version-1 document: its canonical JSON exactly as the pre-version-2 builder wrote it, and that JSON's SHA-256.</summary>
public sealed record CapturedV1Document(string Name, string CanonicalJson, string Sha256);

public static class FinancialDocumentV1BaselineFile
{
    public static string PathOf([CallerFilePath] string here = "") => Path.Combine(Path.GetDirectoryName(here)!, "Fixtures", "financial-documents-v1-baseline.json");

    public static IReadOnlyList<CapturedV1Document> Load() =>
        JsonSerializer.Deserialize<List<CapturedV1Document>>(File.ReadAllText(PathOf())) ?? throw new InvalidOperationException("The version-1 baseline file is empty.");
}

/// <summary>
/// Run ONCE, before template version 2 is written, with <c>ALV_CAPTURE_V1_BASELINE=1</c>: writes the baseline from the builder as it then is. It refuses to overwrite an existing file, so the evidence cannot be
/// regenerated by later code. Without the variable it does nothing.
/// </summary>
public class FinancialDocumentV1BaselineCapture
{
    [Fact]
    public void Capture_the_version_1_baseline_when_asked()
    {
        if (Environment.GetEnvironmentVariable("ALV_CAPTURE_V1_BASELINE") != "1") return;
        var path = FinancialDocumentV1BaselineFile.PathOf();
        Assert.False(File.Exists(path), "The version-1 baseline already exists; it is evidence and must not be regenerated.");
        var captured = FinancialDocumentV1Cases.All.Select(c =>
        {
            object content = c.Type == FinancialDocumentTypes.Statement
                ? FinancialDocumentBuilder.Statement(c.Snapshot, c.CutOffs, c.Envelope)
                : FinancialDocumentBuilder.Receipt(c.Snapshot, c.CutOffs, c.Envelope, c.PaymentNumber!.Value);
            var json = FinancialDocumentBuilder.CanonicalJson(content);
            return new CapturedV1Document(c.Name, json, FinancialDocumentBuilder.Hash(json));
        }).ToList();
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, JsonSerializer.Serialize(captured, new JsonSerializerOptions { WriteIndented = true }));
    }
}
