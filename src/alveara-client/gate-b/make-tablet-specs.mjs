// Gate B (criterion B6, "responsive breakpoint check, desktop + tablet width"): derive TABLET variants of the existing real-backend walkthroughs
// WITHOUT editing them. Each generated spec is the original, byte for byte, except that
//   * every browser context is created at the project's declared tablet viewport (768 x 1024, playwright.config.ts TABLET_VIEWPORT), and
//   * a probe records the largest horizontal overflow of the page (scrollWidth - clientWidth) seen at any moment, in localStorage, and
//   * one final test asserts that no page the walkthrough visited scrolled sideways (<= 1 px) and that the probe really ran.
// The walkthroughs' own assertions and axe scans therefore run at tablet width too: a workflow that needed a wider screen, or a layout that
// overflowed, fails here. The generated files are build output (gitignored); the package for the gate contains them.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const e2e = path.join(here, "..", "e2e");
const out = path.join(here, "tablet-generated");
mkdirSync(out, { recursive: true });

const specs = [
  "patient-registration-real-backend",
  "patient-workspace-real-backend",
  "forms-real-backend",
  "schedule-real-backend",
  "calendar-real-backend",
  "patient-flow-real-backend",
];

const helper = `
// ---- generated by gate-b/make-tablet-specs.mjs: tablet viewport + sideways-scroll probe ----
const TABLET = { width: 768, height: 1024 };
const OVERFLOW_PROBE = \`(() => {
  const key = "__maxOverflowPx";
  const detailKey = "__maxOverflowDetail";
  // Only a STEADY overflow counts: the layout must have a real viewport width (a page being created or navigated momentarily reports a
  // tiny clientWidth and unstyled content, which the first version of this probe mistook for sideways scroll) and the same overflow must
  // be present at two consecutive samples 150 ms apart.
  let prev = 0;
  const sample = () => {
    try {
      const d = document.documentElement;
      const now = d.clientWidth >= 700 ? Math.max(0, d.scrollWidth - d.clientWidth) : 0;
      const o = Math.min(now, prev);
      prev = now;
      if (o > Number(localStorage.getItem(key) ?? "0")) {
        localStorage.setItem(key, String(o));
        const wide = [...document.body.querySelectorAll("*")]
          .map((el) => ({ el, r: el.getBoundingClientRect() }))
          .filter((x) => x.r.width > 0 && x.r.right > d.clientWidth + 1)
          .sort((a, b) => b.r.right - a.r.right)
          .slice(0, 3)
          .map((x) => x.el.tagName.toLowerCase() + "." + String(x.el.className).split(" ").join(".") + " right=" + Math.round(x.r.right) + " text=" + (x.el.textContent || "").trim().slice(0, 40));
        localStorage.setItem(detailKey, JSON.stringify({ px: o, url: location.pathname + location.search, widest: wide }));
      }
    } catch { /* about:blank and the like have no storage */ }
  };
  try { if (localStorage.getItem(key) === null) localStorage.setItem(key, "0"); } catch { /* ignore */ }
  setInterval(sample, 150);
  window.addEventListener("load", sample);
  window.addEventListener("resize", sample);
})()\`;
async function tabletContext(b: Browser) {
  const c = await b.newContext({ viewport: TABLET });
  await c.addInitScript(OVERFLOW_PROBE);
  return c;
}
// ---- end generated helper ----
`;

const lastTest = `
// ---- generated by gate-b/make-tablet-specs.mjs ----
test("TABLET (768x1024): no page this walkthrough visited scrolled sideways", async () => {
  const overflow = await desk.evaluate(() => Number(localStorage.getItem("__maxOverflowPx") ?? "-1"));
  (evidence as Record<string, unknown>).tabletViewport = TABLET;
  (evidence as Record<string, unknown>).tabletMaxSidewaysOverflowPx = overflow;
  (evidence as Record<string, unknown>).tabletMaxSidewaysOverflowDetail = JSON.parse((await desk.evaluate(() => localStorage.getItem("__maxOverflowDetail"))) ?? "null");
  expect(overflow, "the overflow probe must have run").toBeGreaterThanOrEqual(0);
  expect(overflow, "sideways page scroll (px) seen at 768 px wide").toBeLessThanOrEqual(1);
});
`;

for (const name of specs) {
  let text = readFileSync(path.join(e2e, `${name}.spec.ts`), "utf-8");
  const before = (text.match(/newContext\(\)/g) ?? []).length;
  text = text.replace(/deskContext\.browser\(\)!\.newContext\(\)/g, "tabletContext(deskContext.browser()!)");
  text = text.replace(/browser\.newContext\(\)/g, "tabletContext(browser)");
  const left = (text.match(/newContext\(\)/g) ?? []).length;
  if (left !== 0) throw new Error(`${name}: ${left} of ${before} contexts were not converted`);
  // At 768 px the open appointment drawer covers the shell's theme toggle, so the calendar and flow walkthroughs' "switch theme while the drawer is
  // open" step cannot click it (the drawer is a modal-style panel; closing it first is the user's path). Apply the theme the way the toggle does
  // instead - the same attribute and storage key - so the axe scans still run in both themes. The generator fails loudly if the line moves.
  if (name === "calendar-real-backend" || name === "patient-flow-real-backend") {
    const click = 'await page.getByRole("button", { name: /Light|Dark/ }).click();';
    const found = text.split(click).length - 1;
    if (found !== 1) throw new Error(`${name}: expected one theme-toggle click, found ${found}`);
    text = text.replace(click, 'await page.evaluate((t) => { document.documentElement.setAttribute("data-theme", t); localStorage.setItem("alveara-theme", t); }, theme);');
  }
  const lines = text.split("\n");
  const lastImport = lines.map((l, i) => (l.startsWith("import ") ? i : -1)).reduce((a, b) => Math.max(a, b), -1);
  lines.splice(lastImport + 1, 0, helper);
  text = lines.join("\n") + lastTest;
  writeFileSync(path.join(out, `${name}.tablet.spec.ts`), text);
  console.log(`generated ${name}.tablet.spec.ts (${before} contexts at tablet width)`);
}

// Probe control (no backend): the probe must RECORD a steady sideways overflow when one exists and record 0 when there is none, otherwise
// "0 px" in the walkthroughs would prove nothing. Run: TABLET_SPEC=probe-control npx playwright test --config=gate-b/playwright.tablet.config.ts
const control = `import { test, expect } from "@playwright/test";
import type { Browser } from "@playwright/test";
${helper}
test("probe control: a page wider than the tablet viewport IS recorded", async ({ browser }) => {
  const ctx = await tabletContext(browser);
  const page = await ctx.newPage();
  await page.goto("/login");
  await page.evaluate(() => { const d = document.createElement("div"); d.style.cssText = "width:1000px;height:20px;background:#c00"; d.textContent = "wide"; document.body.appendChild(d); });
  await page.waitForTimeout(800);
  const px = await page.evaluate(() => Number(localStorage.getItem("__maxOverflowPx") ?? "-1"));
  expect(px, "a 1000 px element in a 768 px viewport must be recorded").toBeGreaterThan(100);
  await ctx.close();
});
test("probe control: a page that fits is recorded as 0", async ({ browser }) => {
  const ctx = await tabletContext(browser);
  const page = await ctx.newPage();
  await page.goto("/login");
  await page.waitForTimeout(800);
  const px = await page.evaluate(() => Number(localStorage.getItem("__maxOverflowPx") ?? "-1"));
  expect(px, "the login page fits a 768 px viewport").toBe(0);
  await ctx.close();
});
`;
writeFileSync(path.join(out, "probe-control.tablet.spec.ts"), control);
console.log("generated probe-control.tablet.spec.ts");
